h += "    msg('치킨 배달 판매 성공! (+ ' + chickenPrice.toLocaleString() + '원)');"
h += "    updateUI();"
h += "  }"
h += "}"

h += "function upgradeFry() {"
h += "  if (money >= upgradeCost) {"
h += "    money -= upgradeCost;"
h += "    frySpeed += 4;"
h += "    chickenPrice += 1200;"
