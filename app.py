h += "    fryInterval = setInterval(function() {"
h += "      fryProgress += frySpeed;"
h += "      if (fryProgress > 100) { fryProgress = 100; }"
h += "      document.getElementById('bar').style.width = fryProgress + '%';"
h += "      if (fryProgress >= 100) {"
h += "        clearInterval(fryInterval);"
h += "        chickenState = 'cooked';"
h += "        document.getElementById('f-item').innerText = 'READY';"
h += "        msg('황금빛 노릇한 치킨 완성! 클릭하여 건져내세요.');"
h += "      }"
h += "    }, 100);"
h += "  } else if (chickenState === 'cooked') {"
h += "    chickenState = 'plate';"
h += "    let f = document.getElementById('f-item');"
h += "    f.className = 'graphic-item status-none';"
h += "    f.innerText = 'EMPTY';"
h += "    document.getElementById('bar').style.width = '0%';"
h += "    let pl = document.getElementById('pl-item');"
h += "    pl.className = 'graphic-item status-cooked';"
h += "    pl.innerText = 'CHICKEN';"
h += "    msg('포장 완료! 서빙 버튼을 눌러 서빙하세요.');"
h += "    updateUI();"
h += "  }"
h += "}"

h += "function serveChicken() {"
h += "  if (chickenState === 'plate') {"
h += "    money += chickenPrice;"
h += "    chickenState = 'raw';"
h += "    let pl = document.getElementById('pl-item');"
h += "    pl.className = 'graphic-item status-none';"
h += "    pl.innerText = 'EMPTY';"
h += "    let p = document.getElementById('p-item');"
